function fillEnglishTranslations() {
  const data = JSON.parse(fs.readFileSync(EN_PATH, "utf8"));
  let filled = 0;
  for (const entry of data) {
    if (entry.en && entry.en !== "") continue;
    const zh = entry["zh-CN"];
    if (typeof zh !== "string") continue;
    // 优先精确匹配；其次以 trim 后的版本兜底（覆盖结尾 \n 等隐式空白）
    const en = manualMap[zh] ?? manualMap[zh.trim()];
    if (en !== undefined) {
      entry.en = en;
      filled += 1;
    }
  }
  fs.writeFileSync(EN_PATH, `${JSON.stringify(data, null, 2)}\n`);
  const remaining = data.filter((e) => !e.en || e.en === "").length;
  console.log(`填充：${filled} 条；剩余缺失：${remaining} 条；总词条：${data.length} 条`);
}

